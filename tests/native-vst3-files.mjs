import assert from 'node:assert/strict';
import { GuestFiles, GuestFileError } from '../js/native-vst3-files.js';

const encoder = new TextEncoder(), decoder = new TextDecoder();
const source = encoder.encode('abcdef'), files = new GuestFiles(new Map([['/plugin/data.bin', source]]));
const error = (operation, errno) => assert.throws(operation, exception => exception instanceof GuestFileError && exception.errno === errno);
source.fill(0);
const first = files.open('data.bin', 0x1000000);
assert.equal(first, 3); assert.equal(files.control(first, 1), 1); assert.equal(files.control(first, 3), 0);
assert.equal(decoder.decode(files.read(first, 2)), 'ab', 'mounted bytes are snapshotted');
const duplicate = files.duplicate(first);
assert.equal(files.control(duplicate, 1), 0, 'dup clears close-on-exec');
assert.equal(decoder.decode(files.read(duplicate, 2)), 'cd', 'dup shares the open-file position');
assert.equal(files.control(duplicate, 4, 4), 0); assert.equal(files.control(first, 3), 4, 'status flags are shared');
assert.equal(files.control(duplicate, 2, 1), 0);
assert.equal(files.seek(first, -1n, 2), 5n); assert.equal(decoder.decode(files.read(duplicate, 8)), 'f');
assert.equal(files.read(first, 10).length, 0);
assert.equal(files.seek(first, 0x7fffffffffffffffn, 0), 0x7fffffffffffffffn);
assert.equal(files.read(first, 1).length, 0);
error(() => files.seek(first, 1n, 1), 84);
error(() => files.seek(first, -1n, 0), 22);
error(() => files.seek(1, 0n, 0), 29);
assert.equal(files.close(first), 0); error(() => files.close(first), 9);
assert.equal(files.seek(duplicate, 0n, 0), 0n); assert.equal(decoder.decode(files.read(duplicate, 1)), 'a');
error(() => files.open('missing'), 2); error(() => files.open(''), 2);
error(() => files.open('/plugin'), 21); error(() => files.open('/plugin/data.bin/'), 20);
error(() => files.open('data.bin', 1), 30); error(() => files.open('data.bin', 0x200), 30);
error(() => files.open('data.bin', 0x800), 22);
error(() => files.read(1, 1), 9); error(() => files.write(duplicate, encoder.encode('x')), 9);
error(() => files.read(duplicate, -1), 22); error(() => files.read(duplicate, 65 << 20), 22);
error(() => files.control(duplicate, 4, 0x100000000), 22);
assert.throws(() => files.control(duplicate, 999), /Unsupported guest fcntl/);
assert.equal(files.read(0, 1).length, 0);
assert.equal(files.write(1, encoder.encode('stdout')), 6); assert.equal(files.write(2, encoder.encode('stderr')), 6);
assert.equal(files.report().stdout, 'stdout'); assert.equal(files.report().stderr, 'stderr');
assert.equal(files.write(1, new Uint8Array(64 << 10)), (64 << 10) - 6);
error(() => files.write(1, new Uint8Array([1])), 28); assert.equal(files.write(1, new Uint8Array()), 0);
assert.equal(files.path('../../no-host-access'), '/no-host-access');
error(() => files.path('bad\0path'), 22); error(() => files.path('x'.repeat(4097)), 22);
assert.throws(() => new GuestFiles(new Map([['a', new Uint8Array()], ['/plugin/a', new Uint8Array()]])), /Duplicate/);
assert.throws(() => new GuestFiles(new Map(Array.from({ length: 4097 }, (_, index) => [`file-${index}`, new Uint8Array()]))), /count exceeds/);

const bounded = new GuestFiles(new Map([['data', encoder.encode('123')]]));
for (let descriptor = 3; descriptor < 256; descriptor++) assert.equal(bounded.open('data'), descriptor);
error(() => bounded.open('data'), 24);
bounded.setLimits(4n, 16n);
assert.equal(bounded.read(200, 1)[0], 49, 'existing descriptors survive a lowered soft limit');
bounded.close(3); assert.equal(bounded.open('data'), 3); error(() => bounded.open('data'), 24);
error(() => bounded.setLimits(17n, 16n), 22); error(() => bounded.setLimits(16n, 17n), 1);
assert.deepEqual(bounded.report().descriptorLimits, { soft: 4, hard: 16 });
bounded.setLimits(0n, 0n); error(() => bounded.open('data'), 24); error(() => bounded.duplicate(1), 24);
console.log('native files: real descriptor capacity, limits, errno failures, shared offsets, read-only resources, 64-bit seeks and bounded output passed');
