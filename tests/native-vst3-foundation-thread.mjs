 const child = guest.pointer(data + 24), copiedName = send(child, 'name');
 assert.equal(guest.pointer(output + 8), child); assert.notEqual(child, main);
 assert.equal(guest.pointer(data + 64), 0); assert.equal(guest.pointer(data + 80), 1);
 assert.equal(send(child, 'isFinished'), 1); assert.equal(send(child, 'isExecuting'), 0); assert.equal(send(child, 'isMainThread'), 0);
 assert.equal(send(child, 'retainCount'), 1); assert.equal(send(klass, 'isMultiThreaded'), 1);
 assert.notEqual(copiedName, name); assert.equal(guest.core.text(copiedName), 'Arcade worker');
 send(name, 'release'); assert.equal(guest.core.text(copiedName), 'Arcade worker');
 assert.equal(send(child, 'isCancelled'), 0); send(child, 'cancel'); assert.equal(send(child, 'isCancelled'), 1);
 send(child, 'release'); assert.equal(guest.objc.objects.has(child), false); assert.equal(guest.objc.objects.has(copiedName), false);
 const source = guest.objc.foundationString('Main guest'); send(main, 'setName:', source); send(source, 'release');
 assert.equal(guest.core.text(send(main, 'name')), 'Main guest');
 const mainName = send(main, 'name'); send(main, 'setName:', 0); assert.equal(send(main, 'name'), 0); assert.equal(guest.objc.objects.has(mainName), false);
 send(main, 'release'); assert.equal(send(klass, 'currentThread'), main);
 const allocations = guest.allocations.size;
 for (let index = 0; index < 100; index++) assert.equal(send(klass, 'currentThread'), main);
 assert.equal(guest.allocations.size, allocations);
 assert.throws(() => call('object_dispose', main), /managed guest thread/);
